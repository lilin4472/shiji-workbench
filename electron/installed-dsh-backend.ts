export type InstalledDshBackendPreparation =
  | {
      available: true
      runner: AgentRunnerPort
      testModel: () => Promise<DshModelSmokeTestResult>
      searchPort: SearchPort
      /** 归纳通道：把证据表交给模型，拿回结构化归纳（经本地引文校验后才可用）。 */
      synthesize: (payload: EvidenceSynthesisPayload) => Promise<string>
      /** Agent Loop：一次调用跑一轮，返回动作 JSON。 */
      runLoopStep: (payload: LoopStepPayload) => Promise<string>
  planLeadSearch: (payload: LeadPlanPayload) => Promise<string>
    }
  | { available: false; reason: string }

